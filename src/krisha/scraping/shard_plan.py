"""issue #166: дневная порция докачки должна быть смесью города, а не его срезом.

До этой правки очередь докачки деталей (лоты с сайтингом, но без деталей,
`title IS NULL`) сортировалась «кругово» по колонкам `listings.district/rooms`
(#152). Но сайтинг пишет только id/url/price — district/rooms у таких лотов
NULL, партиция `COALESCE(district,'?'), COALESCE(rooms,-1)` схлопывалась в
одну, и очередь фактически работала как `ORDER BY id DESC`: свежесть
публикации вместо географии. Свежих лотов больше там, где выше
оборачиваемость (Бостандыкский), а не там, где больше сток (Алатауский) —
дневная порция имела TVD 0.32–0.35 от состава базы, `time_confounding` в
model_meta застрял на `confounded: true`.

Здесь — чистые функции планировщика, без I/O, чтобы тестировать отдельно от
прохода:

- `largest_remainder_quotas` — дневной лимит докачки раскладывается по шардам
  пропорционально ФАКТИЧЕСКОМУ размеру выдачи шарда (не равными долями:
  цель — повторить состав города, а не выровнять районы искусственно);
- `rotated` — ротация порядка обхода между запусками, чтобы обрыв прохода
  не ампутировал один и тот же хвост алфавита;
- `shard_district` — район из метки шарда (для TVD-контроля порции).
"""

from __future__ import annotations

import math


def largest_remainder_quotas(stock: dict[str, int], cap: int) -> dict[str, int]:
    """Квоты докачки по шардам пропорционально стоку, сумма ровно `cap`.

    Метод наибольших остатков (largest remainder): каждому шарду —
    floor(доля × cap), остаток раздаём по одному шарду с наибольшей дробной
    частью. Ровные доли (1/32) не используем намеренно: они выровняли бы
    районы искусственно, и TVD просто поменял бы знак — цель повторить состав
    выдачи, а не перекосить его в другую сторону.

    Шард со стоком 0 получает квоту 0: недобор по шарду НЕ отдаётся соседям
    в том же проходе — иначе один сбойный/пустой район снова перекосит день.
    Детерминизм: при равных дробных частях выигрывает больший сток, затем
    имя шарда — план воспроизводим от прогона к прогону.
    """
    if cap <= 0 or not stock:
        return {k: 0 for k in stock}
    total = sum(max(0, v) for v in stock.values())
    if total <= 0:
        return {k: 0 for k in stock}
    raw = {k: max(0, v) / total * cap for k, v in stock.items()}
    quotas = {k: int(v) for k, v in raw.items()}
    remainder = cap - sum(quotas.values())
    by_remainder = sorted(
        stock, key=lambda k: (-(raw[k] - quotas[k]), -max(0, stock[k]), k)
    )
    for k in by_remainder[:remainder]:
        quotas[k] += 1
    return quotas


def redistribute_leftover(
    quotas: dict[str, int],
    backlog: dict[str, int],
    stock: dict[str, int | None],
) -> dict[str, int]:
    """Второй проход планировщика (issue #152): довыдача остатка квоты.

    Квота считается от стока выдачи, а окно берётся из backlog'а, поэтому
    шард с мелким backlog'ом свою квоту сжигает впустую (окно меньше квоты),
    и суммарная докачка систематически ниже потолка — на разгоне это binding.
    Остаток раздаётся пропорционально стоку шардам, у которых backlog глубже
    собственной квоты.

    Разделение случаев обязательно (не пересматривает решение #168 о «поле»
    квоты): и донор, и получатель — только шарды с ЗАМЕРЕННЫМ ЭТИМ ПРОХОДОМ
    стоком (stock не None). Незамеренному шарду (не покрыт, бан, усечение по
    max_pages) не достаётся ничего из остатка: у него нет строки стока, с
    которой сверяется batch_tvd, и его докачка ухудшала бы состав порции
    незаметно для метрики — он лечится покрытием и виден через starved_shards.
    Инвариант #166 «сбойный шард не отдаёт свою квоту соседям» сохраняется:
    перераспределяется только остаток от успешно спланированных (замеренных)
    шардов с мелким backlog'ом; квота упавшего шарда (и её невыданный остаток)
    остаётся при нём и компенсируется его курсором в следующих проходах.

    Получатель не может взять больше, чем его backlog глубже квоты: иначе его
    собственное окно снова недоберёт и остаток сгорит во второй раз. Поэтому
    раздача итеративная: перелив у «переполненного» получателя возвращается в
    остаток и перераздаётся следующей итерацией. Сходимость гарантирована:
    каждая итерация либо раздаёт весь остаток, либо заполняет хотя бы один
    шард до его глубины (он выбывает из получателей), а шардов конечное
    число. Детерминизм — от largest_remainder_quotas (тай-брейк по стоку и
    имени), план воспроизводим от прогона к прогону.
    """
    measured = [s for s, st in stock.items() if st is not None]
    extra = {s: 0 for s in quotas}
    leftover = sum(
        max(0, quotas.get(s, 0) - backlog.get(s, 0)) for s in measured
    )
    for _ in range(len(measured) + 1):
        if leftover <= 0:
            break
        # Глубина ещё не заполненных получателей: backlog глубже (квота +
        # уже розданное). Веса — сток выдачи (не глубина): цель порции —
        # повторить состав города, как и в первом проходе.
        capacity = {
            s: backlog.get(s, 0) - quotas.get(s, 0) - extra[s]
            for s in measured
            if backlog.get(s, 0) > quotas.get(s, 0) + extra[s]
        }
        if not capacity:
            break
        give = min(leftover, sum(capacity.values()))
        add = largest_remainder_quotas({s: stock[s] for s in capacity}, give)
        distributed = 0
        for s, a in add.items():
            take = min(a, capacity[s])
            extra[s] += take
            distributed += take
        leftover -= distributed
        if distributed == 0:
            break
    return extra


def rotated(items: list, offset: int) -> list:
    """Циклический сдвиг порядка обхода: проход N стартует не с первого шарда.

    offset — от shard_plan.rotation_offset (шаг, взаимно простой с числом
    шардов): хвост порядка, который ампутирует обрыв по бюджету/бану, гуляет
    по алфавиту день ото дня вместо того, чтобы систематически обрезать один
    и тот же район.
    """
    if not items:
        return items
    o = offset % len(items)
    return items[o:] + items[:o]


def rotation_step(n_shards: int) -> int:
    """Шаг смещения ротации между проходами, взаимно простой с n_shards.

    Шаг +1 сохранял кластеризацию (ревью #166): при покрытии k из 32 шардов
    шард покрыт при (k − offset) mod 32 < k — то есть 32−k проходов подряд
    не покрыт, затем k подряд покрыт. Та же спутанность дня с составом,
    только с длинным периодом. Взаимно простой шаг ≈ 0.4·n разносит
    непокрытие: для n=32 шаг 13 (gcd(13,32)=1) даёт при окне непокрытия
    u = 32−k ≤ 13 максимальную серию подряд непокрытий одного шарда = 1
    проход (при u ≤ 16 — не больше 2) против u подряд при шаге 1. Проверено
    перебором — tests/test_shard_plan.py::test_rotation_step_bounds_uncovered_runs.
    """
    if n_shards <= 1:
        return 1
    step = max(3, round(n_shards * 0.4))
    while math.gcd(step, n_shards) != 1:
        step += 1
    return step


def rotation_offset(pass_seq: int, n_shards: int) -> int:
    """Смещение порядка обхода для прохода с номером pass_seq (сырой счётчик
    из db.sweep_pass_seq). Умножение на взаимно простой шаг — биекция mod n,
    поэтому смещения пробегают все n значений за n проходов, но не подряд."""
    return (pass_seq * rotation_step(n_shards)) % max(1, n_shards)


def shard_district(label: str) -> str:
    """Район из метки шарда «Район Nк» — для TVD-контроля состава порции.

    TVD считаем именно по районам: это ось `time_confounding` в validity.py,
    на которой застрял model_meta (`by="district"`).
    """
    return label.rsplit(" ", 1)[0]
